"""Dataset inspection utility.

Walks the `dataset/` directory, extracts text from every file using the
same layered OCR pipeline the application uses at runtime, and writes a
findings report to `docs/dataset_analysis.md`. Also dumps raw per-file
extracted text under `docs/dataset_text_dump/` for manual inspection.

Usage (from backend/ with the venv active):
    python ../scripts/analyze_dataset.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from PIL import Image  # noqa: E402

from app.services import ocr_service  # noqa: E402

DATASET_DIR = ROOT / "dataset"
DOCS_DIR = ROOT / "docs"
TEXT_DUMP_DIR = DOCS_DIR / "dataset_text_dump"

CATEGORIES = ["Balance Sheet", "Cash Flows", "Profit & Loss", "Invoices"]


def analyze_file(path: Path) -> dict:
    ext = path.suffix.lower()
    info = {"path": str(path.relative_to(ROOT)), "extension": ext}
    try:
        if ext == ".pdf":
            import fitz

            doc = fitz.open(str(path))
            info["page_count"] = doc.page_count
            native_chars = sum(len(doc[i].get_text()) for i in range(doc.page_count))
            info["native_text_chars"] = native_chars
            doc.close()
            doctext = ocr_service.extract_text_from_pdf(str(path))
            info["ocr_used"] = doctext.ocr_used
            info["extracted_text"] = doctext.full_text
            info["extracted_chars"] = len(doctext.full_text)
        else:
            with Image.open(path) as img:
                info["image_size"] = img.size
                info["image_mode"] = img.mode
            info["page_count"] = 1
            doctext = ocr_service.extract_text_from_image(str(path))
            info["ocr_used"] = True
            info["extracted_text"] = doctext.full_text
            info["extracted_chars"] = len(doctext.full_text)
            info["ocr_confidence"] = doctext.pages[0].ocr_confidence
        info["status"] = "OK"
    except Exception as exc:  # analysis script: keep going, record the failure
        info["status"] = f"ERROR: {exc}"
        info["extracted_text"] = ""
    return info


def main() -> None:
    TEXT_DUMP_DIR.mkdir(parents=True, exist_ok=True)
    all_results = {}

    for category in CATEGORIES:
        cat_dir = DATASET_DIR / category
        if not cat_dir.exists():
            print(f"WARNING: category directory missing: {cat_dir}")
            continue
        files = sorted([p for p in cat_dir.iterdir() if p.is_file()])
        print(f"\n=== {category}: {len(files)} files ===")
        results = []
        for f in files:
            print(f"  analyzing {f.name} ...")
            result = analyze_file(f)
            results.append(result)
            dump_name = f"{category.replace(' ', '_').replace('&','and')}__{f.stem}.txt"
            (TEXT_DUMP_DIR / dump_name).write_text(result.get("extracted_text", ""), encoding="utf-8")
        all_results[category] = results

    write_report(all_results)
    print(f"\nDone. Report written to {DOCS_DIR / 'dataset_analysis.md'}")


def write_report(all_results: dict) -> None:
    lines = []
    lines.append("# Dataset Analysis Report")
    lines.append("")
    lines.append(
        "Generated by `scripts/analyze_dataset.py` by running the application's own "
        "OCR pipeline (`app/services/ocr_service.py`) against every file in `dataset/`. "
        "Nothing below is hand-typed; it reflects what the pipeline actually extracted."
    )
    lines.append("")

    total_files = sum(len(v) for v in all_results.values())
    lines.append(f"## Summary\n")
    lines.append(f"- Total files inspected: **{total_files}**")
    for category, results in all_results.items():
        lines.append(f"- {category}: **{len(results)}** files")
    lines.append("")

    for category, results in all_results.items():
        lines.append(f"## {category}")
        lines.append("")
        lines.append("| File | Ext | Pages | Native text chars | OCR used | Extracted chars | Status |")
        lines.append("|---|---|---|---|---|---|---|")
        for r in results:
            name = Path(r["path"]).name
            lines.append(
                f"| {name} | {r.get('extension')} | {r.get('page_count','-')} | "
                f"{r.get('native_text_chars','-')} | {r.get('ocr_used','-')} | "
                f"{r.get('extracted_chars','-')} | {r.get('status')} |"
            )
        lines.append("")

        sample = results[0] if results else None
        if sample and sample.get("extracted_text"):
            lines.append(f"<details><summary>Sample extracted text — {Path(sample['path']).name}</summary>")
            lines.append("")
            lines.append("```")
            lines.append(sample["extracted_text"][:2000])
            lines.append("```")
            lines.append("</details>")
            lines.append("")

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    (DOCS_DIR / "dataset_analysis.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
